        /// <summary>Раскладка строки в клетки. Регистр не важен; неизвестный символ — ошибка.</summary>
        public static PixelTextLayout Layout(string text)
        {
            string upper = text.ToUpperInvariant();
            var layout = new PixelTextLayout { Height = GlyphHeight };
            for (int index = 0; index < upper.Length; index++)
            {
                char c = upper[index];
                if (!Glyphs.TryGetValue(c, out string[] glyph))
                {
                    throw new ArgumentException($"PixelFont: нет глифа для «{c}»", nameof(text));
                }
                int left = index * (GlyphWidth + LetterSpacing);
                for (int y = 0; y < GlyphHeight; y++)
                {
                    for (int x = 0; x < GlyphWidth; x++)
                    {
                        if (glyph[y][x] == '#') layout.Cells.Add((left + x, y));
                    }
                }
            }
            layout.Width = upper.Length == 0 ? 0 : upper.Length * (GlyphWidth + LetterSpacing) - LetterSpacing;
            return layout;
        }
