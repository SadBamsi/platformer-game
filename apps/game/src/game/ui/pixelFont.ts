export interface PixelTextLayout {
  /** Закрашенные клетки: [колонка, строка] от левого верхнего угла строки. */
  cells: Array<[number, number]>;
  /** Ширина строки в клетках. */
  width: number;
  height: number;
}

/** Раскладка строки в клетки. Регистр не важен; неизвестный символ — ошибка. */
export function layoutPixelText(text: string): PixelTextLayout {
  const cells: Array<[number, number]> = [];
  const chars = [...text.toUpperCase()];
  chars.forEach((char, index) => {
    const glyph = GLYPHS[char];
    if (!glyph) throw new Error(`pixelFont: нет глифа для «${char}»`);
    const left = index * (GLYPH_WIDTH + LETTER_SPACING);
    glyph.forEach((row, y) => {
      [...row].forEach((pixel, x) => {
        if (pixel === '#') cells.push([left + x, y]);
      });
    });
  });
  const width = chars.length === 0 ? 0 : chars.length * (GLYPH_WIDTH + LETTER_SPACING) - LETTER_SPACING;
  return { cells, width, height: GLYPH_HEIGHT };
}
