/**
 * tuning.ts
 * ------------------------------------------------------------------------
 * ЕДИНСТВЕННОЕ место со всеми числовыми константами слоя ввода.
 *
 * Все значения — СТАРТОВЫЕ ТОЧКИ для подбора «по ощущению» на реальной игре,
 * а не проверенные/эталонные величины. Источник каждой цифры указан явно:
 * либо это распространённое значение из практики game-feel (без ссылки на
 * конкретную игру, т.к. это не проверялось построчно), либо разумная
 * инженерная оценка. Ничего здесь не стоит воспринимать как факт без
 * тестирования на реальном геймплее и железе.
 */

/** Публичный контракт — можно расширять новыми полями, нельзя сужать. */
export interface InputTuning {
  /**
   * Радиус мёртвой зоны стика (0..1), в радиальном пространстве (по модулю
   * вектора (x,y), не по осям отдельно).
   *
   * Стартовое значение 0.15: типичный диапазон, который в практике game-dev
   * упоминается как «достаточно, чтобы погасить дрейф дешёвых/подержанных
   * стиков, но не съесть полезный диапазон». НЕ измерено на конкретном
   * железе в рамках этой задачи — если у пользователя будет жаловаться на
   * дрейф или на «мёртвый» центр, крутить в первую очередь это значение.
   */
  deadzone: number;

  /**
   * Coyote time (мс) — окно после ухода с земли, в течение которого прыжок
   * всё ещё засчитывается, как будто игрок ещё на платформе.
   *
   * Стартовое значение 100 мс: широко цитируемый в инди-геймдев-сообществе
   * ориентир «около 100-150 мс» для платформеров. Это НЕ измеренная величина
   * для этого конкретного проекта — подбирается по ощущению вместе с
   * гейм-дизайнером/фронтендом на реальной физике прыжка.
   */
  coyoteTimeMs: number;

  /**
   * Jump buffer (мс) — окно ДО приземления, в течение которого ранее нажатый
   * прыжок будет исполнен сразу по касанию земли.
   *
   * Стартовое значение 120 мс: тот же порядок величины, что и coyote time,
   * распространённый ориентир «100-150 мс». Требует подбора по ощущению.
   */
  jumpBufferMs: number;

  /**
   * Показатель степенной кривой отклика стика (magnitude^exponent после
   * мёртвой зоны). 1.0 = линейно, >1 = более точный контроль у центра стика
   * ценой замедленного нарастания скорости, <1 — наоборот, резкий отклик у
   * центра.
   *
   * Стартовое значение 2.0 (квадратичная кривая) — общепринятая в
   * геймдев-практике отправная точка для аналоговых стиков в платформерах,
   * не измерялась под конкретную физику этого проекта.
   */
  stickResponseCurveExponent: number;

  /**
   * Порог value аналогового триггера (0..1), после которого триггер
   * считается «нажатым» как цифровая кнопка, ДАЖЕ если GamepadButton.pressed
   * почему-то не выставлен браузером.
   *
   * Стартовое значение 0.15 — защитный запас на случай неточной калибровки
   * триггера в покое (некоторые триггеры не отдают ровно 0.0 на нуле).
   * Поведение .pressed для триггеров у конкретных браузеров/ОС НЕ
   * ПРОВЕРЕНО в рамках этой задачи — see отчёт, это защитный фолбэк, а не
   * подтверждённая необходимость.
   */
  triggerActivationThreshold: number;

  /**
   * Порог |ось| (0..1), после которого левый стик по X трактуется как
   * нажатая цифровая кнопка MOVE_LEFT/MOVE_RIGHT (для isDown/justPressed —
   * например, для навигации в меню геймпадом).
   *
   * Стартовое значение 0.5 — половина хода стика, обычный ориентир для
   * «стик как D-pad» в UI-навигации.
   */
  digitalAxisThreshold: number;
}

/** Значения по умолчанию — см. комментарии в InputTuning выше по каждому полю. */
export const DEFAULT_TUNING: InputTuning = {
  deadzone: 0.15,
  coyoteTimeMs: 100,
  jumpBufferMs: 120,
  stickResponseCurveExponent: 2.0,
  triggerActivationThreshold: 0.15,
  digitalAxisThreshold: 0.5,
};
